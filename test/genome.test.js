/* gzip: one member, and several back to back (FamilyTreeDNA's autosomal download is two) */
(async () => {
  const zlib = require('zlib');
  const a = 'RSID,CHROMOSOME,POSITION,RESULT\n' + 'rs1,1,5,AA\n'.repeat(5000), b = 'rs2,2,9,CT\n'.repeat(3000);
  assert.strictEqual(await S.gunzip(new Uint8Array(zlib.gzipSync(a))), a);
  assert.strictEqual(await S.gunzip(new Uint8Array(Buffer.concat([zlib.gzipSync(a), zlib.gzipSync(b)]))), a + b);
  await assert.rejects(S.gunzip(new Uint8Array(Buffer.from('not gzip at all'))));
  // a .zip with one deflated text file, as 23andMe, AncestryDNA, MyHeritage and Living DNA send
  const body = 'rsid\tchromosome\tposition\tgenotype\n' + 'rs1\t1\t5\tAA\n'.repeat(200), raw = zlib.deflateRawSync(body), nm = Buffer.from('genome.txt');
  const lh = Buffer.alloc(30), cd = Buffer.alloc(46), eocd = Buffer.alloc(22);
  lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(8, 8); lh.writeUInt32LE(raw.length, 18); lh.writeUInt32LE(body.length, 22); lh.writeUInt16LE(nm.length, 26);
  cd.writeUInt32LE(0x02014b50, 0); cd.writeUInt16LE(8, 10); cd.writeUInt32LE(raw.length, 20); cd.writeUInt32LE(body.length, 24); cd.writeUInt16LE(nm.length, 28); cd.writeUInt32LE(0, 42);
  const cdAt = lh.length + nm.length + raw.length;
  eocd.writeUInt32LE(0x06054b50, 0); eocd.writeUInt16LE(1, 8); eocd.writeUInt16LE(1, 10); eocd.writeUInt32LE(cd.length + nm.length, 12); eocd.writeUInt32LE(cdAt, 16);
  assert.strictEqual(await S.unzip(new Uint8Array(Buffer.concat([lh, nm, raw, cd, nm, eocd]))), body);
  await assert.rejects(S.unzip(new Uint8Array(Buffer.from('PK not really a zip'))));
  console.log('all genome checks pass');
})().catch(e => { console.error(e); process.exit(1); });

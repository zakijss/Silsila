assert.deepStrictEqual([gm('1', 0), gm('1', 500), gm('1', 2500), gm('1', 9999), gm('2', 5)], [0, .5, 3, 4, null]);
{
  const rnd = (seed => () => (seed = (seed * 1103515245 + 12345) % 2147483648) / 2147483648)(42);
  const n = 6000, pos = Int32Array.from({ length: n }, (_, i) => 1000 + i * 1000), A = new Uint8Array(n), B = new Uint8Array(n), C = new Uint8Array(n);
  const code = (a, b) => 1 + 4 * Math.min(a, b) + Math.max(a, b), pick = () => rnd() < .5 ? 0 : 2;   // A or G at every site
  for (let i = 0; i < n; i++) {
    const a1 = pick(), a2 = pick(); A[i] = code(a1, a2);
    // B shares one of A's copies from SNP 2000 to 3999 and both from 2500 to 2999; random elsewhere
    B[i] = i >= 2500 && i < 3000 ? A[i] : i >= 2000 && i < 4000 ? code(a1, pick()) : code(pick(), pick());
    C[i] = code(pick(), pick());
  }
  B[3200] = A[3200] === code(0, 0) ? code(2, 2) : A[3200] === code(2, 2) ? code(0, 0) : B[3200];   // a genotyping error
  const cmAt = p => p / 1e5;   // 1 cM per 100 kb
  const r = S.compareChrom({ pos, gt: A }, { pos, gt: B }, cmAt, { minCM: 7, minSnps: 500 });
  assert.strictEqual(r.half.length, 1);
  assert.ok(r.half[0].start <= pos[2000] && r.half[0].start > pos[1900] && r.half[0].end >= pos[3999] && r.half[0].end < pos[4100], JSON.stringify(r.half));
  assert.ok(Math.abs(r.half[0].cm - 20) < 2);
  assert.strictEqual(r.full.length, 0);   // 500 identical SNPs are only 5 cM here
  const r2 = S.compareChrom({ pos, gt: A }, { pos, gt: B }, cmAt, { minCM: 3, minSnps: 300 });
  assert.ok(r2.full.length === 1 && r2.full[0].start <= pos[2500] && r2.full[0].end >= pos[2999]);
  assert.strictEqual(S.compareChrom({ pos, gt: A }, { pos, gt: C }, cmAt).half.length, 0);   // unrelated
  const all = S.compare({ 1: { pos, gt: A }, X: { pos, gt: A } }, { 1: { pos, gt: B }, X: { pos, gt: A } }, (c, p) => p / 1e5);
  assert.ok(all.segments === 1 && Math.abs(all.half - all.longest.cm) < 1e-9 && all.x > 50);
}
